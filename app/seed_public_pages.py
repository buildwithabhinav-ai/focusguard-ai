# DATABASE SEED
# ============================================================

def seed_translations():

    validate_translations()

    db = SessionLocal()

    inserted = 0
    updated = 0

    try:

        for message_key, languages in TRANSLATIONS.items():

            for language in LANGUAGES:

                translated_text = languages[language]

                existing = (
                    db.query(Translation)
                    .filter(
                        Translation.message_key == message_key,
                        Translation.language == language,
                    )
                    .first()
                )

                if existing:

                    if existing.translated_text != translated_text:
                        existing.translated_text = translated_text
                        updated += 1

                else:

                    db.add(
                        Translation(
                            message_key=message_key,
                            language=language,
                            translated_text=translated_text,
                        )
                    )

                    inserted += 1

        db.commit()

        print("\n==============================================")
        print(" PUBLIC PAGE TRANSLATIONS SEEDED SUCCESSFULLY")
        print("==============================================")
        print(f"Translation keys : {len(TRANSLATIONS)}")
        print(f"Languages        : {len(LANGUAGES)}")
        print(f"Inserted rows    : {inserted}")
        print(f"Updated rows     : {updated}")
        print(
            f"Total expected   : "
            f"{len(TRANSLATIONS) * len(LANGUAGES)}"
        )
        print("==============================================\n")

    except Exception:

        db.rollback()

        print(
            "\nERROR: Translation seeding failed. "
            "Database changes were rolled back.\n"
        )

        raise

    finally:

        db.close()


