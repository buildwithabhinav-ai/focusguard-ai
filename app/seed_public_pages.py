def validate_translations():
    errors = []

    for message_key, languages in TRANSLATIONS.items():

        if len(message_key) > 100:
            errors.append(
                f"message_key exceeds 100 characters: {message_key}"
            )

        missing_languages = [
            language
            for language in LANGUAGES
            if language not in languages
        ]

        if missing_languages:
            errors.append(
                f"{message_key} missing languages: "
                f"{', '.join(missing_languages)}"
            )

        for language, text in languages.items():

            if not isinstance(text, str):
                errors.append(
                    f"{message_key}/{language} is not a string"
                )

            if not text.strip():
                errors.append(
                    f"{message_key}/{language} is empty"
                )

    if errors:
        print("\nTranslation validation failed:\n")

        for error in errors:
            print(f" - {error}")

        raise ValueError(
            f"Translation validation failed with {len(errors)} error(s)."
        )


